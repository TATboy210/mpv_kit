// Generates packages/mpv_kit/lib/src/generated/options.dart: one typed
// MpvOption constant per option of the bundled libmpv.
//
// The source of truth is mpv's own option table, read at runtime through the
// `options` and `option-info/<name>` properties, so types, choices, ranges
// and defaults are exactly those of the library that ships. Summaries come
// from the documentation catalog (tools/gen_catalog.dart).
//
// Usage (from repo root, with the bundled libmpv):
//   MPV_KIT_LIBMPV_PATH=<libmpv> dart run tools/gen_options.dart
// The tool imports mpv_kit, so the previous options.dart must compile; if it
// does not, replace it with an empty `abstract final class MpvOptions {}`.
// ignore_for_file: avoid_relative_lib_imports
import 'dart:io';

import '../packages/mpv_kit/lib/mpv_kit.dart';

const _out = 'packages/mpv_kit/lib/src/generated/options.dart';

const _reserved = {
  'assert', 'break', 'case', 'catch', 'class', 'const', 'continue',
  'default', 'do', 'else', 'enum', 'extends', 'false', 'final', 'finally',
  'for', 'if', 'in', 'is', 'new', 'null', 'rethrow', 'return', 'super',
  'switch', 'this', 'throw', 'true', 'try', 'var', 'void', 'while', 'with',
  // Built-in identifiers that cannot name a class member.
  'abstract', 'as', 'covariant', 'deferred', 'dynamic', 'export',
  'extension', 'external', 'factory', 'Function', 'get', 'implements',
  'import', 'interface', 'late', 'library', 'mixin', 'operator', 'part',
  'required', 'set', 'static', 'typedef',
};

void main() {
  final mpv = Mpv.create(options: const {'vo': 'null', 'ao': 'null'});
  try {
    final names = (mpv.getProperty('options')! as List).cast<String>()..sort();
    final docs = {for (final e in mpvOptions) e.name: e.summary};
    final b = StringBuffer()
      ..writeln(
        '// GENERATED by tools/gen_options.dart from the option table '
        'of libmpv ${mpv.getProperty('mpv-version')} — do not edit.',
      )
      ..writeln(
        '// ignore_for_file: lines_longer_than_80_chars, '
        'constant_identifier_names',
      )
      ..writeln()
      ..writeln("import 'option_types.dart';")
      ..writeln()
      ..writeln('/// Every option of the bundled mpv (${names.length}), typed.')
      ..writeln('///')
      ..writeln(
        '/// Use with [Mpv.getOptionValue] / [Mpv.setOptionValue], or '
        'pass [MpvOption.name]',
      )
      ..writeln('/// to the untyped property API.')
      ..writeln('abstract final class MpvOptions {');
    var count = 0;
    for (final name in names) {
      // `{` / `}` group per-file options on the command line: not settable.
      if (_ident(name).isEmpty) continue;
      final info = mpv.tryGetProperty('option-info/$name');
      if (info is! Map<String, Object?>) continue;
      final type = _type(info['type'] as String? ?? '');
      final choices = (info['choices'] as List?)?.cast<String>() ?? const [];
      final summary = docs[name];
      if (summary != null) b.writeln('  /// ${_doc(summary)}');
      b.writeln('  ///');
      b.writeln(
        '  /// mpv type: ${info['type']}'
        '${choices.isEmpty ? '' : '; choices: ${choices.join(', ')}'}.',
      );
      b.write(
        '  static const ${_ident(name)} = MpvOption<${type.dart}>('
        '${_q(name)}, MpvOptionType.${type.name}',
      );
      if (choices.isNotEmpty) {
        b.write(', choices: [${choices.map(_q).join(', ')}]');
      }
      final min = info['min'], max = info['max'];
      if (min is num) b.write(', min: ${_num(min)}');
      if (max is num) b.write(', max: ${_num(max)}');
      b.writeln(');');
      count++;
    }
    b.writeln('}');
    File(_out).writeAsStringSync(b.toString());
    stdout.writeln('wrote $count options to $_out');
  } finally {
    mpv.dispose();
  }
}

/// Maps an mpv option type to its Dart representation.
({String name, String dart}) _type(String mpvType) => switch (mpvType) {
  'Flag' => (name: 'flag', dart: 'bool'),
  'Integer' || 'Integer64' || 'ByteSize' => (name: 'integer', dart: 'int'),
  'Double' || 'Float' || 'Time' || 'Aspect' => (name: 'real', dart: 'double'),
  'Choice' => (name: 'choice', dart: 'String'),
  _ => (name: 'string', dart: 'String'),
};

String _ident(String name) {
  final parts = name.split(RegExp('[^a-zA-Z0-9]+')).where((p) => p.isNotEmpty);
  var id = parts.indexed
      .map((e) => e.$1 == 0 ? e.$2 : e.$2[0].toUpperCase() + e.$2.substring(1))
      .join();
  if (RegExp('^[0-9]').hasMatch(id)) id = 'o$id';
  return _reserved.contains(id) ? '${id}_' : id;
}

String _num(num v) {
  if (v.isInfinite || v.isNaN || v.abs() > 1e15) {
    return v.isNegative ? '-double.maxFinite' : 'double.maxFinite';
  }
  return v == v.truncate() ? '${v.toInt()}' : '$v';
}

String _doc(String s) => s
    .replaceAll('\n', ' ')
    .replaceAll('[', r'\[')
    .replaceAllMapped(RegExp('<[^>]*>'), (m) => '`${m[0]}`');

String _q(String s) =>
    "'${s.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$')}'";
