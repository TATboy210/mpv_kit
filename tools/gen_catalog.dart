// Generates packages/mpv_kit/lib/src/generated/catalog.dart from mpv's own
// documentation (DOCS/man/input.rst + options.rst), so the catalog of
// properties, commands and options always matches the bundled mpv version.
//
// Usage (from repo root):  dart run tools/gen_catalog.dart
import 'dart:io';

const _docs = 'native/mpv/DOCS/man';
const _out = 'packages/mpv_kit/lib/src/generated/catalog.dart';

void main() {
  final input = File('$_docs/input.rst').readAsLinesSync();
  final options = File('$_docs/options.rst').readAsLinesSync();

  final props = _section(input, 'Property list', 'Inconsistencies between options and properties');
  final cmds = _section(input, 'List of Input Commands', 'Input Command Prefixes');

  final properties = _entries(props, RegExp(r'^``([a-z0-9][a-z0-9/<>_\-]*)``(.*)$'));
  final commands = _entries(cmds, RegExp(r'^``([a-z][a-z0-9\-]*)(?: [^`]*)?``(.*)$'));
  final optionEntries = _entries(options, RegExp(r'^``--([a-z0-9][a-z0-9\-]*)(?:=[^`]*)?``(.*)$'));

  final b = StringBuffer()
    ..writeln('// GENERATED by tools/gen_catalog.dart from mpv DOCS/man — do not edit.')
    ..writeln('// ignore_for_file: lines_longer_than_80_chars')
    ..writeln()
    ..writeln("import 'catalog_types.dart';")
    ..writeln()
    ..writeln('/// Properties documented in input.rst (${properties.length}).')
    ..writeln('const mpvProperties = <MpvCatalogEntry>[');
  for (final e in properties) {
    b.writeln('  MpvCatalogEntry(${_q(e.name)}, ${_q(e.summary)}, writable: ${e.flags.contains('RW')}),');
  }
  b
    ..writeln('];')
    ..writeln()
    ..writeln('/// Input commands documented in input.rst (${commands.length}).')
    ..writeln('const mpvCommands = <MpvCatalogEntry>[');
  for (final e in commands) {
    b.writeln('  MpvCatalogEntry(${_q(e.name)}, ${_q(e.summary)}),');
  }
  b
    ..writeln('];')
    ..writeln()
    ..writeln('/// Options documented in options.rst (${optionEntries.length}); every option is also a property.')
    ..writeln('const mpvOptions = <MpvCatalogEntry>[');
  for (final e in optionEntries) {
    b.writeln('  MpvCatalogEntry(${_q(e.name)}, ${_q(e.summary)}, writable: true),');
  }
  b.writeln('];');

  File(_out)
    ..createSync(recursive: true)
    ..writeAsStringSync(b.toString());
  stdout.writeln('properties=${properties.length} commands=${commands.length} '
      'options=${optionEntries.length} -> $_out');
}

typedef _Entry = ({String name, String flags, String summary});

List<String> _section(List<String> lines, String start, String end) {
  final s = lines.indexWhere((l) => l.trim() == start);
  final e = lines.indexWhere((l) => l.trim() == end, s + 1);
  if (s < 0) throw StateError('section "$start" not found');
  return lines.sublist(s, e < 0 ? lines.length : e);
}

/// Each entry is a ``name`` line at column 0 followed by an indented paragraph.
List<_Entry> _entries(List<String> lines, RegExp head) {
  final seen = <String>{};
  final out = <_Entry>[];
  for (var i = 0; i < lines.length; i++) {
    final m = head.firstMatch(lines[i]);
    if (m == null) continue;
    final name = m.group(1)!;
    if (!seen.add(name)) continue;
    final flags = m.group(2) ?? '';
    final text = <String>[];
    for (var j = i + 1; j < lines.length; j++) {
      final l = lines[j];
      if (l.trim().isEmpty) {
        if (text.isNotEmpty) break;
        continue;
      }
      if (!l.startsWith(' ')) break;
      text.add(l.trim());
    }
    out.add((name: name, flags: flags, summary: _firstSentence(text.join(' '))));
  }
  return out;
}

String _firstSentence(String s) {
  final clean = s.replaceAll('``', '').replaceAll(RegExp(r'\s+'), ' ');
  final dot = clean.indexOf('. ');
  final first = dot < 0 ? clean : clean.substring(0, dot + 1);
  return first.length > 200 ? '${first.substring(0, 197)}...' : first;
}

String _q(String s) =>
    "'${s.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$')}'";
